STATEMENT = r"""
Write `token_kl(logits_pol, logits_ref, mask)` for logits of shape `(T, V)` from the policy and the reference model on the same sequence.

- At each position, $\text{KL}_t = \sum_v p_t(v)\,(\log p_t(v) - \log q_t(v))$ with $p = \text{softmax}$ of the policy logits and $q$ of the reference logits. Use log-softmax so large logits do not overflow.
- `mask (T,)` marks the response tokens (1) versus prompt or padding (0).

Return a dict with `per_token` (all $T$ values, with masked positions set to 0.0), `mean` (mean over masked-in positions, 0.0 if none) and `total` (sum over masked-in positions).
"""

STARTER = '''import numpy as np

def token_kl(logits_pol, logits_ref, mask):
    """Exact KL(policy || reference) at each response token."""
    p = np.exp(logits_pol) / np.exp(logits_pol).sum(1, keepdims=True)
    q = np.exp(logits_ref) / np.exp(logits_ref).sum(1, keepdims=True)
    kl = (q * np.log(q / p)).sum(1)
    return {"per_token": kl.tolist(), "mean": float(kl.mean()), "total": float(kl.sum())}
'''

SOLUTION = '''import numpy as np

def _logsm(z):
    z = np.asarray(z, float)
    m = z.max(1, keepdims=True)
    return z - m - np.log(np.exp(z - m).sum(1, keepdims=True))

def token_kl(logits_pol, logits_ref, mask):
    lp, lq = _logsm(logits_pol), _logsm(logits_ref)
    kl = (np.exp(lp) * (lp - lq)).sum(1)
    m = np.asarray(mask, bool)
    kl = np.where(m, kl, 0.0)
    n = int(m.sum())
    return {"per_token": kl.tolist(), "mean": float(kl.sum() / n) if n else 0.0, "total": float(kl.sum())}
'''

HINTS = [
    'KL(policy || reference) weights by the policy’s probabilities; the order matters.',
    'log_softmax(z) = z - max - log(sum(exp(z - max))).',
    'Prompt tokens were not generated by the policy, so they do not count towards its drift.',
]

def _case(seed, T, V, shift, scale):
    g = np.random.default_rng(seed)
    ref = scale * g.normal(size=(T, V))
    return (ref + shift * g.normal(size=(T, V)), ref, (np.arange(T) >= T // 3).astype(int))

