EXPLANATION = r"""
## Why averaging works
Each return $G_t$ that follows a visit to $s$ is a sample whose expectation is $V^\pi(s)$ (by definition of the value). Averaging $n$ of them is unbiased for first-visit MC and converges as $n \to \infty$. Every-visit MC is slightly biased for finite samples, because returns from repeat visits in one episode are correlated, but it is also consistent and often has lower variance. Tests 5 and 6 make the difference concrete: one episode that sits in state 3 for three steps.

## Complexity
$O(\text{total steps})$ time with the backward pass. Computing each $G_t$ with its own forward sum is $O(L^2)$ per episode, a common slow version.

## Common bugs
- Using a `seen` set shared across episodes, so first-visit drops every later episode's visits.
- Dividing by zero for unvisited states (gives `nan`).
- Computing returns from the *last* visit rather than the first in first-visit mode.

## Interview follow-ups
- MC vs TD(0): which has higher variance, which has bias, and which can learn from incomplete episodes?
- How would you turn this into an incremental update $V(s) \leftarrow V(s) + \alpha (G - V(s))$, and when is a constant $\alpha$ preferable to $1/n$?
"""
