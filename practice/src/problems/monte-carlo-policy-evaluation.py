STATEMENT = r"""
Monte Carlo evaluation estimates $V^\pi(s)$ by averaging the returns that followed visits to $s$ in complete episodes generated by $\pi$. No model and no bootstrapping: just sample returns.

Write `mc_evaluate(episodes, n_states, gamma=1.0, first_visit=True)` and return `(V, counts)`.

## Inputs
- `episodes`: a list of episodes. Each episode is a pair `(states, rewards)` of equal-length lists: `states[t]` is the state at step $t$ and `rewards[t]` is the reward received on leaving it. Every episode is complete (it terminates after its last step) and has at least one step.
- `n_states`: states are integers in `[0, n_states)`.

## Rules
- The return from step $t$ of an episode of length $L$ is $G_t = \sum_{k=t}^{L-1} \gamma^{k-t} r_k$.
- **First-visit**: each episode contributes at most one return per state, the one from that state's first occurrence in the episode.
- **Every-visit**: each occurrence of a state contributes its own return.
- $V(s)$ is the plain average of all contributed returns.

## Output
- `V`: float array `(n_states,)`. States that never appear get `0.0`.
- `counts`: int array `(n_states,)`, how many returns were averaged into each state.
"""

