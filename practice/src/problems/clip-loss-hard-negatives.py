STATEMENT = r"""
A CLIP model trained on random batches can match images to captions by spotting nouns alone, so it never learns word order or counting. Hard negatives fix this: for every image add a caption that is almost right (objects swapped, a number changed).

Write `clip_loss_hard_negatives(img, txt, hard, tau)` with `img`, `txt`, `hard` all shape `(n, d)`, where `hard[i]` is the hard negative caption for image `i`:

- L2-normalise every row.
- Image to text: each image scores all `2n` captions, $[\,\text{txt};\ \text{hard}\,]$, with logits $\langle u_i, v_j \rangle / \tau$. The right answer is caption `i`.
- Text to image: each true caption scores the `n` images. The right answer is image `i`. Hard negatives are not used as queries.
- Return the mean of the two directions' average cross-entropy, a float.
"""

STARTER = '''import numpy as np

def clip_loss_hard_negatives(img, txt, hard, tau):
    """Symmetric CLIP loss where image-to-text also sees hard negative captions."""
    u = np.asarray(img, float); v = np.asarray(txt, float)
    z = u @ v.T / tau
    lse = np.log(np.exp(z).sum(1))
    return float(np.mean(lse - np.diag(z)))
'''

SOLUTION = '''import numpy as np

def _ce(z):
    m = z.max(1, keepdims=True)
    lse = (m + np.log(np.exp(z - m).sum(1, keepdims=True)))[:, 0]
    return float(np.mean(lse - z[np.arange(len(z)), np.arange(len(z))]))

def clip_loss_hard_negatives(img, txt, hard, tau):
    nz = lambda a: (lambda a: a / np.linalg.norm(a, axis=1, keepdims=True))(np.asarray(a, float))
    u, v, h = nz(img), nz(txt), nz(hard)
    i2t = u @ np.vstack([v, h]).T / tau
    t2i = v @ u.T / tau
    return 0.5 * (_ce(i2t) + _ce(t2i))
'''

HINTS = [
    'Stack the true and hard captions into one (2n, d) matrix; the correct column for row i is still column i.',
    'The two directions now have different numbers of candidates, so compute each cross-entropy separately and average them.',
    'Subtract the row maximum before exponentiating; with tau = 0.01 the logits reach 100.',
]

def _case(seed, n, d, tau, closeness):
    g = np.random.default_rng(seed)
    img = g.normal(size=(n, d))
    txt = img + 0.3 * g.normal(size=(n, d))
    hard = closeness * txt + (1 - closeness) * g.normal(size=(n, d))
    return (img, txt, hard, tau)

