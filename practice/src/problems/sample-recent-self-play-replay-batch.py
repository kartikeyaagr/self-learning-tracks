SOLUTION = '''import numpy as np

def sample_replay(game_lengths, window, batch_size, seed):
    positions = [(g, m) for g, n in enumerate(game_lengths) for m in range(n)]
    kept = positions[-window:]                      # slicing past the start just keeps everything
    if not kept:
        return []
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(kept), size=batch_size)
    return [kept[int(i)] for i in idx]
'''

