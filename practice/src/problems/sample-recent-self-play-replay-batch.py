STATEMENT = r"""
The training loop does not learn from all self-play ever played. It keeps a sliding window of the most recent positions (AlphaGo Zero used the last 500,000 games) and draws minibatches uniformly from it, so stale data from much weaker networks fades out.

Positions are identified by `(game, move)`: game `g` (0-based, oldest first) has `game_lengths[g]` positions numbered `0 .. game_lengths[g] - 1`.

Write `sample_replay(game_lengths, window, batch_size, seed)`.

## Steps
1. List every position in chronological order: game 0's moves in order, then game 1's, and so on.
2. Keep only the **last** `window` positions of that list (all of them if there are fewer). `window >= 1`.
3. Create `rng = np.random.default_rng(seed)` and draw `idx = rng.integers(0, M, size=batch_size)`, where `M` is the number of kept positions. This samples **with** replacement.
4. Return the list `[kept[i] for i in idx]`, each entry a `(game, move)` tuple of Python ints.

If there are no positions at all, return `[]` without drawing.
"""

