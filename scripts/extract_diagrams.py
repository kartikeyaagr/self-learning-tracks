"""Extract the house diagram renderer from System Design 101's template into the Astro site.

    uv run --no-project scripts/extract_diagrams.py

The diagram code in system-design-101/src/app.html is pure string-building JS. This script copies it, unchanged,
into two modules so the site renders the same 14 diagram types:
  site/src/lib/diagrams.gen.mjs   build time: flow, seq, layers, state, tree, timeline, compare, matrix, bars → HTML/SVG
  site/src/lib/figs.gen.js        browser: step-through controls, animated packets, interactive widgets
  site/public/css/house.css       the house stylesheet (tokens, layout, lesson and diagram styles)
Re-run after updating System Design 101. Only the shims at the top of each file are written here.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = (ROOT / 'sources' / 'system-design-101' / 'src' / 'app.html').read_text(encoding='utf-8')
code = src[src.index('<script>', src.index('</header>')) + len('<script>'):src.rindex('</script>')]


def region(start, end):
    i, j = code.index(start), code.index(end)
    assert i < j, (start, end)
    return code[i:j]


static = region('// ---------- diagrams ----------', '// ---------- interactive diagrams ----------')
live = region('// ---------- interactive diagrams ----------', '// ---------- notes markup ----------')
# AV() measures the window; at build time use the lesson column's max width (the page CSS scales SVGs down).
static = re.sub(r'const AV = \(\) => \{.*?\};', 'const AV = () => 720;', static, count=1, flags=re.S)

HEADER = '// GENERATED by scripts/extract_diagrams.py from sources/system-design-101/src/app.html. Do not edit.\n'
# diagram() emits the step controls, which are defined at the top of the interactive region: include those lines.
ctl = live[:live.index('\n', live.index('const dgCtl = '))]
(ROOT / 'site/src/lib/diagrams.gen.mjs').write_text(HEADER + "import { esc, inl } from './inline.mjs';\n"
                                                    + ctl + '\n' + static + '\nexport { diagram };\n', encoding='utf-8')

(ROOT / 'site/src/lib/figs.gen.js').write_text(HEADER + """import { esc, inl } from './inline-basic.mjs';   // no KaTeX in the browser bundle
const $ = s => document.querySelector(s);
const RM = matchMedia('(prefers-reduced-motion: reduce)').matches;
""" + live + '\nexport { initFigs };\n', encoding='utf-8')
css = src[src.index('<style>') + len('<style>'):src.index('</style>')]
(ROOT / 'site/public/css').mkdir(parents=True, exist_ok=True)
(ROOT / 'site/public/css/house.css').write_text('/* GENERATED by scripts/extract_diagrams.py. Do not edit. */\n' + css, encoding='utf-8')
print(f'engine.gen.css {len(css)} chars, diagrams.gen.mjs {len(static)} chars, figs.gen.js {len(live)} chars')
