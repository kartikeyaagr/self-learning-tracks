"""Extract each exported course's own stylesheet and figure code for the Astro site.

    uv run --no-project scripts/extract_courses.py

For every claude.ai export this writes
  site/public/css/<dir>.css            the course's own stylesheet (its figures depend on its own classes)
  site/src/lib/figs/<dir>.gen.js       browser module: the course's helpers, markup renderer and figure code, plus
                                       mount(root): renders course-specific blocks (.dg-raw placeholders) with the course's
                                       own render() and starts its interactive figures exactly as the original page did.
System Design 101's code is handled by scripts/extract_diagrams.py (house diagrams + its widgets) and is reused by the
engine courses. Re-run after re-exporting a course.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = '// GENERATED by scripts/extract_courses.py from {src}. Do not edit.\n'
EXPORTS = {
    'ml-maths-course':       dict(src='index.html',     css='index.html',        mount='mountViz();'),
    'inference-eng-course':  dict(src='index.html',     css='index.html',        mount='mountWidgets(root);'),
    'ai-engineering-course': dict(src='assets/app.js',  css='assets/styles.css', mount='mountWidgets(root);'),
    # AI Research's notebook + quiz blocks keep their own saved state (exercises, quiz answers, checkpoints) on the
    # course's localStorage key, so its state code is kept and the blocks re-render in place.
    'ai-research-track-web': dict(src='index.html',     css='index.html',        keep_state=True, include=('topic blocks',),
                                  mount="""mountViz(root);
  const box = document.getElementById('air-blocks');
  if (box){ const B = JSON.parse(box.dataset.blocks); rerender = () => { box.innerHTML = B.map(blockHTML).join(''); wireBlocks({blocks: B}); mountViz(box); }; rerender(); }""",
                                  patch=[('href="sheets/${', 'href="/courses/ai-research-track-web/sheets/${'),
                                         ('`<a href="#l${key(id)}">${id}</a>`', '`<a href="${(window.__lessonUrl || {})[id] || \'#\'}">${id}</a>`')]),
}
# Page-level sections: the Astro site provides these itself.
SKIP = ('game layer', 'spaced review', 'chrome', 'pages', 'diagnostic', 'review deck', 'search palette', 'feedback',
        'routing', 'writes', 'shared persistence', 'topic blocks', 'module cover art')
DROP = re.compile(r'^(const (DATA|RAW|MATH|NB|NBZIP|TXT|ALL|PARTS) = |const txt = |function ls(Get|Set)\(|Object\.assign\(st|\[\'done\'|let db)')
KEEP_STATE_DROP = re.compile(r'^(const (DATA|RAW|MATH|NB|NBZIP|TXT|ALL|PARTS) = |const txt = )')
STUBS = {  # called by figure code but defined in skipped sections; harmless no-ops on the new site
    'award': 'function award(){}', 'toast': 'function toast(){}', 'confetti': 'function confetti(){}', 'chrome': 'function chrome(){}',
    'rerender': 'function rerender(){}', 'bump': 'function bump(){}', 'xp': 'function xp(){ return 0; }', 'side': 'function side(){}',
    'lsSet': 'function lsSet(){}', 'saveMisc': 'function saveMisc(){}', 'fitMath': 'function fitMath(){}',
    'route': 'function route(){}', 'go': 'function go(){}', 'openPal': 'function openPal(){}',
}


def script_of(path):
    s = path.read_text(encoding='utf-8')
    if path.suffix == '.js':
        return s
    tags = [m.start() for m in re.finditer(r'<script>', s)]
    i = max(t for t in tags if 'const DATA' in s[t:t + 2_000_000] or 'const RAW' in s[t:t + 2_000_000])
    return s[i + len('<script>'):s.index('</script>', i)]


def sections(code):
    marks = [(m.start(), m.group(1)) for m in re.finditer(r'^// -{3,} ?(.*?) ?-{3,}\s*$', code, re.M)]
    first = marks[0][0]
    out = [('prelude', code[:first])]
    for (a, name), nxt in zip(marks, marks[1:] + [(len(code), None)]):
        out.append((name, code[a:nxt[0]]))
    return out


def build(dirname, cfg):
    d = ROOT / dirname
    code = script_of(d / cfg['src'])
    for a, b in cfg.get('patch', []):
        assert code.count(a) == 1, f'{dirname}: patch anchor {a!r} found {code.count(a)}x'
        code = code.replace(a, b)
    drop = KEEP_STATE_DROP if cfg.get('keep_state') else DROP
    parts = []
    for name, body in sections(code):
        if name == 'prelude':
            body = '\n'.join(l for l in body.split('\n') if not drop.match(l))
            body += '\nconst DATA = [], ALL = [], PARTS = [], MATH = [];\n'
        elif name.lower().startswith(SKIP) and not name.lower().startswith(cfg.get('include', ())):
            continue
        else:   # the original page's startup call can sit at the end of a figure section; the site starts things itself
            body = re.sub(r'^(route|init|boot|start)\(\);\s*$', '', body, flags=re.M)
        parts.append(body)
    js = '\n'.join(parts)
    if cfg.get('keep_state'):
        js = js.replace('function rerender(', 'function __unused_rerender(')   # mount() supplies rerender
        js += '\nlet rerender = () => {};\nconst view = document.getElementById(\'view\');\n'
    stubs = '\n'.join(v for k, v in STUBS.items() if not re.search(rf'(function {k}\(|const {k} = |let {k} = )', js))
    if cfg.get('keep_state'):
        stubs = stubs.replace('function lsSet(){}', '')
    out = (HEADER.format(src=f'{dirname}/{cfg["src"]}') + '/* eslint-disable */\n' + js + '\n' + stubs + '\n'
           + """export function mount(root){
  // Course-specific blocks were kept as their original source; render them with this course's own render().
  root.querySelectorAll('.dg-raw').forEach(el => { const t = document.createElement('div'); t.innerHTML = render(el.dataset.src); el.replaceWith(...t.childNodes); });
  """ + cfg['mount'] + '\n}\n')
    fig = ROOT / 'site/src/lib/figs' / f'{dirname}.gen.js'
    fig.parent.mkdir(parents=True, exist_ok=True)
    fig.write_text(out, encoding='utf-8')
    src = (d / cfg['css']).read_text(encoding='utf-8')
    css = src if cfg['css'].endswith('.css') else src[src.index('<style>') + 7:src.index('</style>')]
    cssf = ROOT / 'site/public/css' / f'{dirname}.css'
    cssf.parent.mkdir(parents=True, exist_ok=True)
    cssf.write_text(css, encoding='utf-8')
    print(f'{dirname:24} figs {len(out) // 1024:>4} KB   css {len(css) // 1024:>3} KB')


if __name__ == '__main__':
    for k, v in EXPORTS.items():
        build(k, v)
