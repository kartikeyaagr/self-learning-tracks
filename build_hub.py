def js_value(src, name):
    """Parse the JSON literal after `const <name> = ` (the exports inline their data as JSON)."""
    i = src.index(f'const {name} = ') + len(f'const {name} = ')
    return json.JSONDecoder().raw_decode(src, i)[0]

def mins(l):
    # Mirrors each course's own `mins()`: AI Research stores it, the others estimate at 180 wpm.
    if 'mins' in l: return l['mins'] or 2
    return max(2, math.ceil(len((l.get('a') or ' '.join(l.get('n', []))).split()) / 180))

QUESTIONS = {}   # "trackkey:lessonid" -> self-check question + model answer, for interview theory rounds


def questions(t, src, mods):
    """Each lesson's q/s as the interview page should show them. ML Maths stores maths as ⟦n⟧ references into a MATH
    table of pre-rendered HTML, and AI Research stores HTML entities, so those two are shipped as HTML."""
    math = js_value(src, 'MATH') if 'const MATH = ' in src else None
    out = {}
    for m in mods:
        for l in m['lessons']:
            q, a = l.get('q'), l.get('s')
            if not q or not a:
                continue
            html = t['key'] == 'air-fanout-v1' and not l.get('a')       # add-on lessons there are markdown
            if math and ('\u27e6' in q + a):
                import html as H
                md = lambda x: re.sub(r'`(.+?)`', r'<code>\1</code>', re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', x))   # the course's own inl()
                fix = lambda x: re.sub('\u27e6(\\d+)\u27e7', lambda g: math[int(g.group(1))], md(H.escape(x, quote=False)))
                q, a, html = fix(q), fix(a), True
            out[f"{t['key']}:{l['id']}"] = {'q': q, 's': a, 'html': html, 't': l['t'], 'c': t['name']}
    return out


def extract(t):
    src = (ROOT / t['dir'] / t['src']).read_text(encoding='utf-8')
    engine = src if t['src'] == 'index.html' else (ROOT / t['dir'] / 'assets/app.js').read_text(encoding='utf-8')
    page = (ROOT / t['dir'] / 'index.html').read_text(encoding='utf-8')
    css = page if t['src'] == 'index.html' else (ROOT / t['dir'] / 'assets/styles.css').read_text(encoding='utf-8')
    accent = re.findall(r'--accent:(#[0-9A-Fa-f]{6})', css)[:2]           # [light, dark] from :root and the dark block
    pix = re.search(r'--pix:\s*([^;]+);', css).group(1)                  # the course's display font for accent words
    logo = re.search(r'<a class="brand" href="#">(<svg.*?</svg>)', page, re.S).group(1)
    mods = js_value(src, 'RAW')['modules'] if 'const RAW = ' in src else js_value(src, 'DATA')
    num = lambda pat: ast.literal_eval(re.search(pat, engine).group(1))  # JS literals use single quotes
    if t['key'] != 'practice':
        QUESTIONS.update(questions(t, src, mods))
    return {**{k: t[k] for k in ('dir', 'key', 'name')}, 'unit': t.get('unit', 'lessons'), 'accent': accent, 'pix': pix, 'logo': logo,
            'LV': num(r'const LV = (\[[^\]]*\])'), 'LVN': num(r'const LVN = (\[[^\]]*\])'),
            'goal': num(r'const GOAL = (\d+)'),
            'modules': [{'n': m['n'], 'name': m['name'], 'lessons': [[l['id'], l['t'], mins(l)] for l in m['lessons']]}
                        for m in mods]}

# Borrows the course's own .ibtn look. Inline display is required: the courses hide .ibtn above 960px
# (it's the mobile menu button there), and this link must show at every width.
