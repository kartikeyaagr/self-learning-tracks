"""Build hub-data.js from the five course exports, and add a "back to hub" button to each course.

Re-run after re-exporting any course:  uv run build_hub.py
Safe to re-run: an existing back link is replaced, never duplicated.
"""
import ast, json, math, re
from pathlib import Path

ROOT = Path(__file__).parent
# Order = suggested study order. `src` is the file holding the course's DATA (AI Eng keeps it in assets/).
# Accent colours and logos are read from each course, so the hub always matches the course pages.
TRACKS = [
    dict(dir='ml-maths-course',       key='mlmaths',       name='ML Maths',              src='index.html'),
    dict(dir='ai-research-track-web', key='air-fanout-v1', name='AI Research',           src='index.html'),
    dict(dir='ai-engineering-course', key='aieng',         name='AI Engineering',        src='assets/data.js'),
    dict(dir='inference-eng-course',  key='ieng',          name='Inference Engineering', src='index.html'),
    dict(dir='system-design-101',     key='sdsd',          name='System Design',         src='index.html'),
    # Practice follows the same page contract; it is generated by practice/src/build.py, so run that first.
    dict(dir='practice',              key='practice',      name='Practice Lab',          src='index.html', unit='problems'),
]
EXPECTED = {'mlmaths': 47, 'air-fanout-v1': 108, 'aieng': 43, 'ieng': 226, 'sdsd': 200}   # practice grows, so it isn't pinned

def js_value(src, name):
    """Parse the JSON literal after `const <name> = ` (the exports inline their data as JSON)."""
    i = src.index(f'const {name} = ') + len(f'const {name} = ')
    return json.JSONDecoder().raw_decode(src, i)[0]

def mins(l):
    # Mirrors each course's own `mins()`: AI Research stores it, the others estimate at 180 wpm.
    if 'mins' in l: return l['mins'] or 2
    return max(2, math.ceil(len((l.get('a') or ' '.join(l.get('n', []))).split()) / 180))

def extract(t):
    src = (ROOT / t['dir'] / t['src']).read_text(encoding='utf-8')
    engine = src if t['src'] == 'index.html' else (ROOT / t['dir'] / 'assets/app.js').read_text(encoding='utf-8')
    page = (ROOT / t['dir'] / 'index.html').read_text(encoding='utf-8')
    css = page if t['src'] == 'index.html' else (ROOT / t['dir'] / 'assets/styles.css').read_text(encoding='utf-8')
    accent = re.findall(r'--accent:(#[0-9A-Fa-f]{6})', css)[:2]           # [light, dark] from :root and the dark block
    pix = re.search(r'--pix:\s*([^;]+);', css).group(1)                  # the course's display font for accent words
    logo = re.search(r'<a class="brand" href="#">(<svg.*?</svg>)', page, re.S).group(1)
    mods = js_value(src, 'RAW')['modules'] if 'const RAW = ' in src else js_value(src, 'DATA')
    num = lambda pat: ast.literal_eval(re.search(pat, engine).group(1))  # JS literals use single quotes
    return {**{k: t[k] for k in ('dir', 'key', 'name')}, 'unit': t.get('unit', 'lessons'), 'accent': accent, 'pix': pix, 'logo': logo,
            'LV': num(r'const LV = (\[[^\]]*\])'), 'LVN': num(r'const LVN = (\[[^\]]*\])'),
            'goal': num(r'const GOAL = (\d+)'),
            'modules': [{'n': m['n'], 'name': m['name'], 'lessons': [[l['id'], l['t'], mins(l)] for l in m['lessons']]}
                        for m in mods]}

# Borrows the course's own .ibtn look. Inline display is required: the courses hide .ibtn above 960px
# (it's the mobile menu button there), and this link must show at every width.
HUB_LINK = ('<!--hub-link--><a class="ibtn" href="../index.html" aria-label="All tracks" title="All tracks" '
            'style="display:inline-flex;color:var(--ink);flex:none">'
            '<svg width="18" height="18" viewBox="0 0 18 18" fill="none" stroke="currentColor" stroke-width="1.6">'
            '<rect x="2.5" y="2.5" width="5" height="5" rx="1.4"/><rect x="10.5" y="2.5" width="5" height="5" rx="1.4"/>'
            '<rect x="2.5" y="10.5" width="5" height="5" rx="1.4"/><rect x="10.5" y="10.5" width="5" height="5" rx="1.4"/></svg></a>')

def add_back_link(t):
    """Insert (or refresh) the hub button as the first item in the course header."""
    p = ROOT / t['dir'] / 'index.html'
    s = re.sub(r'<!--hub-link-->.*?</a>', '', p.read_text(encoding='utf-8'), count=1, flags=re.S)
    assert s.count('<header class="top">') == 1, f'{p}: header markup changed, update add_back_link'
    p.write_text(s.replace('<header class="top">', '<header class="top">' + HUB_LINK), encoding='utf-8')

if __name__ == '__main__':
    out = [extract(t) for t in TRACKS]
    for t in out:  # self-check: lesson totals match each course's README
        n = sum(len(m['lessons']) for m in t['modules'])
        assert n == EXPECTED.get(t['key'], n), (t['key'], n)
        assert len(t['LVN']) >= len(t['LV']), t['key']
        assert len(t['accent']) == 2 and t['logo'].startswith('<svg'), t['key']
        print(f"{t['name']:<22} {len(t['modules']):>2} modules {n:>4} lessons")
    (ROOT / 'hub-data.js').write_text('// Generated by build_hub.py. Do not edit.\nconst TRACKS = '
                                      + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
    for t in TRACKS: add_back_link(t)
